"""# Recommendation Engine"""

def recommendation_engine(df):

    data = df.copy()
    recommendations = []

    # Ensure correct data types
    data["Date"] = pd.to_datetime(data["Date"])
    data["Revenue"] = pd.to_numeric(data["Revenue"])
    data["Ad Spend"] = pd.to_numeric(data["Ad Spend"])
    data["Conversions"] = pd.to_numeric(data["Conversions"])

    # Overall KPIs
    total_revenue = data["Revenue"].sum()
    total_spend = data["Ad Spend"].sum()
    total_conversions = data["Conversions"].sum()

    overall_roas = (
        total_revenue / total_spend if total_spend > 0 else 0
    )

    # Helper function
    def add_recommendation(priority, category, finding, action, evidence):
        recommendations.append({
            "Priority": priority,
            "Category": category,
            "Finding": finding,
            "Recommendation": action,
            "Evidence": evidence
        })

    # 1. Marketing Channel Recommendations
    channel_stats = data.groupby("Channel").agg(
        Revenue=("Revenue", "sum"),
        Ad_Spend=("Ad Spend", "sum"),
        Conversions=("Conversions", "sum"),
        Records=("Revenue", "size")
    )

    channel_stats["ROAS"] = np.where(
        channel_stats["Ad_Spend"] > 0,
        channel_stats["Revenue"] / channel_stats["Ad_Spend"],
        np.nan
    )

    for channel, row in channel_stats.iterrows():

        if pd.isna(row["ROAS"]):
            continue

        if row["ROAS"] >= overall_roas * 1.10:
            add_recommendation(
                "High",
                "Marketing",
                f"{channel} is an above-average channel.",
                f"Consider gradually increasing {channel} budget "
                "through controlled budget tests.",
                f"ROAS: {row['ROAS']:.2f} vs "
                f"Overall ROAS: {overall_roas:.2f}"
            )

        elif row["ROAS"] < overall_roas * 0.80:
            add_recommendation(
                "High",
                "Marketing",
                f"{channel} is performing below average.",
                f"Review {channel} campaigns, targeting, "
                "and advertising costs before allocating more budget.",
                f"ROAS: {row['ROAS']:.2f} vs "
                f"Overall ROAS: {overall_roas:.2f}"
            )

    # 2. Service Performance
    service_stats = data.groupby("Service Type").agg(
        Revenue=("Revenue", "sum"),
        Ad_Spend=("Ad Spend", "sum"),
        Conversions=("Conversions", "sum")
    )

    service_stats["ROAS"] = np.where(
        service_stats["Ad_Spend"] > 0,
        service_stats["Revenue"] / service_stats["Ad_Spend"],
        np.nan
    )

    for service, row in service_stats.iterrows():

        if pd.notna(row["ROAS"]) and row["ROAS"] >= overall_roas * 1.10:
            add_recommendation(
                "Medium",
                "Service",
                f"{service} has strong advertising efficiency.",
                f"Prioritize testing additional campaigns for {service}.",
                f"ROAS: {row['ROAS']:.2f}"
            )

        elif pd.notna(row["ROAS"]) and row["ROAS"] < overall_roas * 0.80:
            add_recommendation(
                "Medium",
                "Service",
                f"{service} has relatively low advertising efficiency.",
                f"Review pricing, promotion, and campaign targeting "
                f"for {service}.",
                f"ROAS: {row['ROAS']:.2f}"
            )

    # 3. Customer Retention
    customer_revenue = data.groupby("Customer Type")["Revenue"].sum()

    returning_revenue = customer_revenue.get("Returning", 0)
    returning_share = (
        returning_revenue / total_revenue * 100
        if total_revenue > 0 else 0
    )

    if returning_share < 50:
        add_recommendation(
            "High",
            "Customer Retention",
            "Returning customers contribute less than half of revenue.",
            "Introduce loyalty programs, repeat-purchase offers, "
            "and customer retention campaigns.",
            f"Returning customer revenue share: {returning_share:.2f}%"
        )
    else:
        add_recommendation(
            "Medium",
            "Customer Retention",
            "Returning customers represent a strong revenue contribution.",
            "Maintain customer loyalty initiatives and test "
            "personalized offers to improve repeat purchases.",
            f"Returning customer revenue share: {returning_share:.2f}%"
        )

    # 4. Monthly Revenue Trend
    monthly_revenue = (
        data.set_index("Date")
        .resample("ME")["Revenue"]
        .sum()
    )

    if len(monthly_revenue) >= 2:

        current = monthly_revenue.iloc[-1]
        previous = monthly_revenue.iloc[-2]

        growth = (
            (current - previous) / previous * 100
            if previous > 0 else np.nan
        )

        if pd.notna(growth) and growth < -5:
            add_recommendation(
                "High",
                "Revenue Trend",
                "Revenue declined significantly in the latest month.",
                "Investigate channel, service, and regional "
                "performance to identify the main causes.",
                f"Monthly revenue change: {growth:.2f}%"
            )

        elif pd.notna(growth) and growth > 5:
            add_recommendation(
                "Low",
                "Revenue Trend",
                "Revenue increased in the latest month.",
                "Identify the segments driving growth and test "
                "whether their performance can be sustained.",
                f"Monthly revenue change: +{growth:.2f}%"
            )

    # 5. Regional Performance
    region_stats = data.groupby("Region").agg(
        Revenue=("Revenue", "sum"),
        Ad_Spend=("Ad Spend", "sum")
    )

    region_stats["ROAS"] = np.where(
        region_stats["Ad_Spend"] > 0,
        region_stats["Revenue"] / region_stats["Ad_Spend"],
        np.nan
    )

    valid_regions = region_stats.dropna(subset=["ROAS"])

    if len(valid_regions) >= 2:

        best_region = valid_regions["ROAS"].idxmax()
        worst_region = valid_regions["ROAS"].idxmin()

        add_recommendation(
            "Medium",
            "Regional Performance",
            f"{best_region} has the highest regional ROAS.",
            f"Study successful campaigns in {best_region} "
            f"and test transferable strategies in {worst_region}.",
            f"Best: {best_region} ({valid_regions.loc[best_region, 'ROAS']:.2f}), "
            f"Lowest: {worst_region} "
            f"({valid_regions.loc[worst_region, 'ROAS']:.2f})"
        )

    # 6. Data Quality Alert
    zero_conversion_revenue = data.loc[
        (data["Conversions"] == 0) & (data["Revenue"] > 0),
        "Revenue"
    ].sum()

    if zero_conversion_revenue > 0:
        add_recommendation(
            "High",
            "Data Quality",
            "Some records have revenue but zero recorded conversions.",
            "Review conversion tracking and revenue attribution "
            "before making final campaign decisions.",
            f"Revenue in zero-conversion records: "
            f"{zero_conversion_revenue:,.2f}"
        )

    # Final output
    result = pd.DataFrame(recommendations)

    priority_order = {"High": 0, "Medium": 1, "Low": 2}

    if not result.empty:
        result["_sort"] = result["Priority"].map(priority_order)
        result = (
            result.sort_values("_sort")
            .drop(columns="_sort")
            .reset_index(drop=True)
        )

    return result


